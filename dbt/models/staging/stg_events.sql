{{ config(unique_key='EVENT_ID') }}
select
    "event_id" as EVENT_ID,
    "group_id" as GROUP_ID,
    coalesce("venue_id"::string, '-1') as VENUE_ID,
    trim("event_name") as EVENT_NAME,
    try_to_timestamp("event_time"::string) as EVENT_TIME,
    try_to_timestamp("created"::string) as CREATED_AT,
    try_to_timestamp("updated"::string) as UPDATED_AT,
    trim("description") as DESCRIPTION,
    "duration" as DURATION,
    trim("event_url") as EVENT_URL,
    "headcount" as HEADCOUNT,
    trim("how_to_find_us") as HOW_TO_FIND_US,
    "maybe_rsvp_count" as MAYBE_RSVP_COUNT,
    trim("photo_url") as PHOTO_URL,
    "utc_offset" as UTC_OFFSET,
    trim("visibility") as VISIBILITY,
    "waitlist_count" as WAITLIST_COUNT,
    trim("why") as WHY,
    "yes_rsvp_count" as YES_RSVP_COUNT,
    trim("event_status") as STATUS,
    "rsvp_limit" as RSVP_LIMIT,
    trim("fee.accepts") as FEE_ACCEPTS,
    "fee.amount" as FEE_AMOUNT,
    trim("fee.currency") as FEE_CURRENCY,
    trim("fee.description") as FEE_DESCRIPTION,
    trim("fee.label") as FEE_LABEL,
    trim("fee.required") as FEE_REQUIRED,
    try_to_timestamp("group.created"::string) as GROUP_CREATED_AT,
    "group.group_lat" as GROUP_LATITUDE,
    "group.group_lon" as GROUP_LONGITUDE,
    trim("group.join_mode") as GROUP_JOIN_MODE,
    trim("group.name") as GROUP_NAME,
    trim("group.urlname") as GROUP_URLNAME,
    trim("group.who") as GROUP_WHO,
    "rating.average" as RATING_AVERAGE,
    "rating.count" as RATING_COUNT,
    trim("venue.address_1") as VENUE_ADDRESS_1,
    trim("venue.address_2") as VENUE_ADDRESS_2,
    trim("venue.city") as VENUE_CITY,
    trim("venue.country") as VENUE_COUNTRY,
    "venue.lat" as VENUE_LATITUDE,
    trim("venue.localized_country_name") as VENUE_LOCALIZED_COUNTRY_NAME,
    "venue.lon" as VENUE_LONGITUDE,
    trim("venue.name") as VENUE_NAME,
    trim("venue.phone") as VENUE_PHONE,
    "venue.repinned" as VENUE_REPINNED,
    trim("venue.state") as VENUE_STATE,
    "venue.zip" as VENUE_ZIP,
    CURRENT_TIMESTAMP() as LOADED_DATE
from {{ source('raw', 'events') }}
